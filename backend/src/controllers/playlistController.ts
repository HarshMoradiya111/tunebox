export async function createUserPlaylist(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const { name, description } = req.body;
    if (!name) {
      res.status(400).json({ success: false, error: "Name is required" });
      return;
    }

    const playlist = new Playlist({
      name,
      description: description || "",
      isUserCreated: true,
      tracks: []
    });

    await playlist.save();
    res.status(201).json({ success: true, data: playlist });
  } catch (error) {
    next(error);
  }
}

export async function getUserPlaylists(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const playlists = await Playlist.find({ isUserCreated: true }).sort({ createdAt: -1 }).lean();
    res.json({ success: true, data: playlists });
  } catch (error) {
    next(error);
  }
}

export async function addTrackToPlaylist(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const { id } = req.params;
    const { trackId } = req.body;

    if (!mongoose.Types.ObjectId.isValid(trackId)) {
      res.status(400).json({ success: false, error: "Invalid track ID" });
      return;
    }

    const playlist = await Playlist.findOne({ _id: id, isUserCreated: true });
    if (!playlist) {
      res.status(404).json({ success: false, error: "User playlist not found" });
      return;
    }

    // Convert trackId to ObjectId to use with mongoose array
    const objId = new mongoose.Types.ObjectId(trackId);

    // Push if not already present
    if (!playlist.tracks.includes(objId)) {
      playlist.tracks.push(objId);
      playlist.totalTracks = playlist.tracks.length;
      await playlist.save();
    }

    res.json({ success: true, data: playlist });
  } catch (error) {
    next(error);
  }
}

export async function removeTrackFromPlaylist(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const { id, trackId } = req.params;

    const playlist = await Playlist.findOne({ _id: id, isUserCreated: true });
    if (!playlist) {
      res.status(404).json({ success: false, error: "User playlist not found" });
      return;
    }

    const objId = new mongoose.Types.ObjectId(trackId as string);
    
    // Remove track
    playlist.tracks = playlist.tracks.filter(tid => !tid.equals(objId));
    playlist.totalTracks = playlist.tracks.length;
    await playlist.save();

    res.json({ success: true, data: playlist });
  } catch (error) {
    next(error);
  }
}

export async function deleteUserPlaylist(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const { id } = req.params;
    const playlist = await Playlist.findOneAndDelete({ _id: id });
    
    if (!playlist) {
      res.status(404).json({ success: false, error: "Playlist not found" });
      return;
    }

    res.json({ success: true, message: "Playlist deleted" });
  } catch (error) {
    next(error);
  }
}

export async function renameUserPlaylist(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const { id } = req.params;
    const { name, description } = req.body;
    
    const playlist = await Playlist.findOne({ _id: id, isUserCreated: true });
    
    if (!playlist) {
      res.status(404).json({ success: false, error: "User playlist not found" });
      return;
    }

    if (name !== undefined) playlist.name = name;
    if (description !== undefined) playlist.description = description;

    await playlist.save();
    res.json({ success: true, data: playlist });
  } catch (error) {
    next(error);
  }
}
